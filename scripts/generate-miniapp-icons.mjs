/**
 * 小程序 lucide 图标注册表生成器（REQ-009 滚动：小程序图标体系化）。
 * 从 lucide-react 包内源码提取 SVG 节点 → 生成 data-URI 注册表（weapp 无 DOM/SVG 组件，
 * 用 CSS mask + background-color: currentColor 渲染，天然跟随主题色）。
 *
 *   node scripts/generate-miniapp-icons.mjs   # 仓库根运行
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const iconsDir = join(here, "..", "node_modules", "lucide-react", "dist", "esm", "icons");
const outFile = join(here, "..", "apps", "miniapp", "src", "components", "lucide-icon", "icons.generated.ts");

/** 小程序端用到的图标清单（kebab-case = lucide 官方文件名） */
const NAMES = [
  "pencil", "trash-2", "sparkles", "star", "sun", "target", "plus", "rotate-ccw",
  "repeat", "calendar", "calendar-days", "check", "chevron-left", "chevron-right",
  "chevron-down", "chevron-up", "search", "x", "mic", "bell", "clock", "download",
  "ellipsis", "file-text", "settings", "user", "trending-up", "arrow-left",
  "arrow-right", "log-out", "eye", "camera", "image-plus", "link-2", "list-todo",
  "wallet", "coins", "utensils", "smile", "clipboard-list", "notebook-pen",
  "users", "heart", "cake", "alarm-clock", "refresh-cw", "triangle-alert",
  "hourglass", "circle", "check-circle-2", "info", "pause", "zap", "bar-chart-3",
  "landmark", "credit-card", "receipt", "sprout", "network", "gem", "key-round",
  "home", "send", "play",
];

function readNode(name, depth = 0) {
  if (depth > 3) throw new Error("alias 链过深");
  const src = readFileSync(join(iconsDir, `${name}.mjs`), "utf8");
  if (!src.includes("__iconData")) {
    // 别名文件：export { default } from './X.mjs' —— 跟随（lucide 旧名→新名）
    const alias = src.match(/from '\.\/([a-z0-9-]+)\.mjs'/);
    if (!alias) throw new Error("既无 __iconData 也无别名导出");
    return readNode(alias[1], depth + 1);
  }
  return src;
}

function toKebabNode(name) {
  // __iconData = {...}; 是受信任的本地包源码：以表达式求值后取 node 数组
  const src = readNode(name);
  const m = src.match(/const __iconData = (\{[\s\S]*?\});/);
  if (!m) throw new Error("__iconData not found");
  const data = new Function(`return (${m[1]})`)();
  const inner = data.node
    .map(([tag, attrs]) => {
      const a = Object.entries(attrs)
        .filter(([k]) => k !== "key")
        .map(([k, v]) => `${k.replace(/([A-Z])/g, "-$1").toLowerCase()}="${String(v).replace(/&/g, "&amp;").replace(/"/g, "&quot;")}"`)
        .join(" ");
      return `<${tag} ${a}/>`;
    })
    .join("");
  // data URI：# 必须转义；单引号包裹外层
  const svg = `data:image/svg+xml;utf8,<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 ${data.size} ${data.size}' fill='none' stroke='black' stroke-width='2' stroke-linecap='round' stroke-linejoin='round'>${inner}</svg>`.replace(/#/g, "%23");
  return svg;
}

const entries = [];
const missing = [];
for (const name of NAMES) {
  try {
    entries.push(`  ${name.replace(/-/g, "_")}: ${JSON.stringify(toKebabNode(name))},`);
  } catch {
    missing.push(name);
  }
}
if (missing.length) {
  console.error(`[miniapp-icons] 缺失图标: ${missing.join(", ")}`);
  process.exit(1);
}

const out = `/**
 * GENERATED by scripts/generate-miniapp-icons.mjs（源：lucide-react ${"1.47.0"} 官方 SVG）——勿手改。
 * 用法：<LucideIcon name="pencil" size={13} color="var(--ink-mute)" />
 */
export const ICONS: Record<string, string> = {
${entries.join("\n")}
};
`;
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, out);
console.log(`[miniapp-icons] ${entries.length} icons -> ${outFile}`);
